    /// Applies a JSON object of overrides. Keys match field names case-insensitively, with or without
    /// underscores (so both the original Go names, e.g. `LaserValue`, and `laser_value` work).
    pub fn apply_json(&mut self, raw: &str) -> Result<(), String> {
        let over: serde_json::Value = serde_json::from_str(raw).map_err(|e| e.to_string())?;
        let over = over.as_object().ok_or("BOT_PARAMS is not a JSON object")?;
        let mut cur = serde_json::to_value(&*self).map_err(|e| e.to_string())?;
        let cur_obj = cur.as_object_mut().unwrap();
        let norm = |s: &str| s.replace('_', "").to_ascii_lowercase();
        for (k, v) in over {
            let nk = norm(k);
            if let Some(key) = cur_obj.keys().find(|ck| norm(ck) == nk).cloned() {
                cur_obj.insert(key, v.clone());
            }
        }
        *self = serde_json::from_value(cur).map_err(|e| e.to_string())?;
        Ok(())
    }
